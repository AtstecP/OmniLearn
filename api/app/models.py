"""ORM models (schema owned by Alembic migrations in api/migrations).

Every row has a UUID primary key generated by the server; learners never
supply IDs. Hierarchy and links are plain foreign keys:

* roadmap_nodes.parent_node_id -> another lesson in the same subject
* tests.node_id -> a lesson in the same subject (or NULL for the question bank)
* reading_questions.reading_id -> its passage
* progress / attempt rows -> users(id) and the lesson, card or question

The database also enforces non-empty titles, 2-20 options with a valid
correct_index, and valid progress statuses (see migration 0003). Python
defaults (uuid4) let the importer build a whole nested course in memory and
insert it in one flush.
"""
from datetime import date, datetime, timezone
from uuid import UUID as PythonUUID, uuid4
from sqlalchemy import Boolean, Date, DateTime, ForeignKey, ForeignKeyConstraint, Integer, Numeric, String, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column
from .database import Base


def now_utc():
    return datetime.now(timezone.utc)


def uuid_pk():
    return mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid4)


class User(Base):
    __tablename__ = "users"
    id: Mapped[PythonUUID] = uuid_pk()
    email: Mapped[str] = mapped_column(String(320), unique=True, nullable=False, index=True)
    full_name: Mapped[str] = mapped_column(String(120), nullable=False)
    password_hash: Mapped[str] = mapped_column(String(255), nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class Subject(Base):
    __tablename__ = "subjects"
    id: Mapped[PythonUUID] = uuid_pk()
    owner_user_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[str | None] = mapped_column(Text)
    target_level: Mapped[str | None] = mapped_column(String(32))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())


class RoadmapNode(Base):
    """A lesson. Lessons without a parent are the main steps of the roadmap."""
    __tablename__ = "roadmap_nodes"
    __table_args__ = (
        UniqueConstraint("subject_id", "id", name="uq_roadmap_nodes_subject_id"),
        ForeignKeyConstraint(["subject_id", "parent_node_id"], ["roadmap_nodes.subject_id", "roadmap_nodes.id"], name="fk_roadmap_nodes_parent"),
    )
    id: Mapped[PythonUUID] = uuid_pk()
    subject_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    parent_node_id: Mapped[PythonUUID | None] = mapped_column(UUID(as_uuid=True))
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    level: Mapped[str | None] = mapped_column(String(32))
    order_index: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    content_markdown: Mapped[str] = mapped_column(Text, nullable=False, default="")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())


class TestQuestion(Base):
    """A multiple-choice question; node_id links it to a lesson, NULL keeps it in the bank only."""
    __tablename__ = "tests"
    __table_args__ = (
        ForeignKeyConstraint(["subject_id", "node_id"], ["roadmap_nodes.subject_id", "roadmap_nodes.id"], name="fk_tests_node"),
    )
    id: Mapped[PythonUUID] = uuid_pk()
    subject_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    node_id: Mapped[PythonUUID | None] = mapped_column(UUID(as_uuid=True))
    order_index: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    prompt: Mapped[str] = mapped_column(Text, nullable=False)
    options: Mapped[list] = mapped_column(JSONB, nullable=False)
    correct_index: Mapped[int] = mapped_column(Integer, nullable=False)
    explanation: Mapped[str] = mapped_column(Text, nullable=False, default="")
    tags: Mapped[list[str]] = mapped_column(ARRAY(String), nullable=False, default=list)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())


class VocabCard(Base):
    __tablename__ = "vocab_cards"
    id: Mapped[PythonUUID] = uuid_pk()
    subject_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    term: Mapped[str] = mapped_column(String(255), nullable=False)
    part_of_speech: Mapped[str | None] = mapped_column(String(64))
    definition: Mapped[str] = mapped_column(Text, nullable=False)
    example_sentence: Mapped[str | None] = mapped_column(Text)
    image_url: Mapped[str | None] = mapped_column(String(1024))
    audio_url: Mapped[str | None] = mapped_column(String(1024))
    tags: Mapped[list[str]] = mapped_column(ARRAY(String), nullable=False, default=list)
    source: Mapped[str] = mapped_column(String(64), default="manual")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class ReadingPassage(Base):
    __tablename__ = "reading_passages"
    id: Mapped[PythonUUID] = uuid_pk()
    subject_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("subjects.id", ondelete="CASCADE"), nullable=False)
    order_index: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    cefr_level: Mapped[str | None] = mapped_column(String(16))
    content: Mapped[str] = mapped_column(Text, nullable=False)
    audio_url: Mapped[str | None] = mapped_column(String(1024))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())


class ReadingQuestion(Base):
    __tablename__ = "reading_questions"
    id: Mapped[PythonUUID] = uuid_pk()
    reading_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("reading_passages.id", ondelete="CASCADE"), nullable=False)
    order_index: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    prompt: Mapped[str] = mapped_column(Text, nullable=False)
    options: Mapped[list] = mapped_column(JSONB, nullable=False)
    correct_index: Mapped[int] = mapped_column(Integer, nullable=False)
    explanation: Mapped[str] = mapped_column(Text, nullable=False, default="")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class UserNodeProgress(Base):
    __tablename__ = "user_node_progress"
    user_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    node_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("roadmap_nodes.id", ondelete="CASCADE"), primary_key=True)
    status: Mapped[str] = mapped_column(String(32), nullable=False, default="in_progress")
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class UserVocabProgress(Base):
    __tablename__ = "user_vocab_progress"
    user_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    card_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("vocab_cards.id", ondelete="CASCADE"), primary_key=True)
    interval_days: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    ease_factor: Mapped[float] = mapped_column(Numeric(4, 2), nullable=False, default=2.5)
    consecutive_correct: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    due_date: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, default=now_utc)
    last_reviewed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    status: Mapped[str] = mapped_column(String(32), nullable=False, default="learning")


class UserTestAttempt(Base):
    __tablename__ = "user_test_attempts"
    id: Mapped[PythonUUID] = uuid_pk()
    user_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    test_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("tests.id", ondelete="CASCADE"), nullable=False)
    selected_index: Mapped[int] = mapped_column(Integer, nullable=False)
    is_correct: Mapped[bool] = mapped_column(Boolean, nullable=False)
    is_flagged_mistake: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    consecutive_correct_in_retest: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    attempted_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class UserActivityDay(Base):
    __tablename__ = "user_activity_days"
    user_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True)
    day: Mapped[date] = mapped_column(Date, primary_key=True)
    actions: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
